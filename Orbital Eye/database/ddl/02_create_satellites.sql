SET SERVEROUTPUT ON;
-- SQL*Plus terminates a SQL statement at a blank line by default, which would
-- truncate the CREATE TABLE below (it contains a blank line before the FOREIGN
-- KEY constraint). SQLBLANKLINES keeps blank lines inside statements intact.
SET SQLBLANKLINES ON;

-- Identity column is GENERATED BY DEFAULT (not ALWAYS) because the seed files
-- insert explicit primary keys (1..N for REALTIME, 9001/9002 for ACCIDENT).
-- GENERATED ALWAYS would raise ORA-32795 and abort the entire seed load.
CREATE TABLE satellites (
    satellite_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    norad_id NUMBER NOT NULL UNIQUE,
    satellite_name VARCHAR2(100) NOT NULL,
    operator_id NUMBER NOT NULL,
    status VARCHAR2(20) NOT NULL CHECK (status IN ('ACTIVE', 'DESTROYED', 'DEORBITED', 'UNKNOWN')),
    mass_kg NUMBER,
    dataset_tag VARCHAR2(20) NOT NULL CHECK (dataset_tag IN ('REALTIME', 'ACCIDENT')),

    CONSTRAINT fk_sat_operator
        FOREIGN KEY (operator_id)
        REFERENCES operators(operator_id)
);

CREATE INDEX idx_satellites_dataset_tag ON satellites(dataset_tag);
CREATE INDEX idx_satellites_status ON satellites(status);
CREATE INDEX idx_satellites_operator ON satellites(operator_id);

