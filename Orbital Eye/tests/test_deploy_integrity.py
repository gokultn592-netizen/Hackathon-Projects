"""
Test Suite: Database Deploy Integrity & Frontend Type Safety

Guards the fixes that allowed a broken build to ship unnoticed:

1. Every DDL file referenced by deploy.sh / deploy.bat actually exists in
   database/ddl (previously `01_create_operators.sql` and
   `02_create_satellites.sql` were referenced but missing, so a clean deploy
   aborted at step 01).
2. Every core table has a CREATE TABLE statement somewhere in database/ddl
   (previously `operators` and `satellites` had none, so the schema was only
   reproducible out-of-band).
3. Identity columns are GENERATED BY DEFAULT, not ALWAYS. The seed files insert
   explicit primary keys, and GENERATED ALWAYS raises ORA-32795, aborting the
   whole seed load.
4. Every DDL file sets SQLBLANKLINES ON. SQL*Plus terminates a statement at a
   blank line by default, which silently truncated the CREATE TABLE statements
   (a blank line preceded the CONSTRAINT clause).
5. The frontend has a tsconfig.json and `npm run build` runs the type check, so
   an undefined-variable ReferenceError cannot reach production again.
"""

import os
import re
import json
import subprocess
import pytest

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DDL_DIR = os.path.join(ROOT_DIR, "database", "ddl")
FRONTEND_DIR = os.path.join(ROOT_DIR, "frontend")

CORE_TABLES = [
    "operators",
    "satellites",
    "tle_sets",
    "encounter_pairs",
    "encounter_events",
    "debris",
]


def _ddl_files():
    return sorted(f for f in os.listdir(DDL_DIR) if f.endswith(".sql"))


def _read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def test_every_ddl_file_referenced_by_deploy_exists():
    """deploy.sh and deploy.bat must not reference a DDL file that is missing."""
    referenced = set()

    deploy_sh = _read(os.path.join(ROOT_DIR, "database", "deploy.sh"))
    referenced.update(re.findall(r'"(\d\d_[a-z0-9_]+\.sql)"', deploy_sh))

    deploy_bat = _read(os.path.join(ROOT_DIR, "database", "deploy.bat"))
    referenced.update(re.findall(r"(\d\d_[a-z0-9_]+\.sql)", deploy_bat))

    assert referenced, "deploy scripts should reference DDL files"

    on_disk = set(_ddl_files())
    missing = sorted(referenced - on_disk)
    assert not missing, f"deploy scripts reference missing DDL files: {missing}"


def test_all_core_tables_have_a_create_table_statement():
    """Every core table must be creatable from the repo's DDL."""
    combined = "\n".join(
        _read(os.path.join(DDL_DIR, f)) for f in _ddl_files()
    ).lower()

    for table in CORE_TABLES:
        pattern = rf"create\s+table\s+(if\s+not\s+exists\s+)?{table}\b"
        assert re.search(pattern, combined), (
            f"No CREATE TABLE statement for '{table}' in database/ddl — "
            f"the schema would not be reproducible from the repository."
        )


def test_identity_columns_are_by_default_not_always():
    """
    Seed files insert explicit primary keys (1..N and 9001+). GENERATED ALWAYS
    raises ORA-32795 and aborts the entire seed load.
    """
    for f in _ddl_files():
        content = _read(os.path.join(DDL_DIR, f))
        for m in re.finditer(r"generated\s+always\s+as\s+identity", content, re.IGNORECASE):
            line_no = content[: m.start()].count("\n") + 1
            pytest.fail(
                f"{f}:{line_no} uses GENERATED ALWAYS AS IDENTITY. The seed files "
                f"insert explicit IDs, which would raise ORA-32795 and abort the load. "
                f"Use GENERATED BY DEFAULT AS IDENTITY."
            )


def test_ddl_files_enable_sqlblanklines():
    """
    SQL*Plus ends a statement at a blank line by default, silently truncating
    CREATE TABLE statements that contain a blank line before a CONSTRAINT clause.
    """
    for f in _ddl_files():
        content = _read(os.path.join(DDL_DIR, f))
        assert re.search(r"set\s+sqlblanklines\s+on", content, re.IGNORECASE), (
            f"{f} does not enable SQLBLANKLINES. A blank line inside a CREATE TABLE "
            f"statement will truncate it in SQL*Plus."
        )


def test_seed_files_enable_sqlblanklines():
    """Seed files should also be blank-line safe."""
    seed_dir = os.path.join(ROOT_DIR, "output")
    for f in ("seed_realtime.sql", "seed_accident.sql"):
        path = os.path.join(seed_dir, f)
        assert os.path.exists(path), f"{f} is missing from output/"
        content = _read(path)
        assert re.search(r"set\s+sqlblanklines\s+on", content, re.IGNORECASE), (
            f"{f} does not enable SQLBLANKLINES"
        )


def test_frontend_has_tsconfig_and_build_typechecks():
    """
    A tsconfig.json plus a type-check step in the build script is what prevents
    undefined-variable ReferenceErrors from shipping (the `selectedEncounter`
    crash passed `vite build` because Vite strips types without checking them).
    """
    tsconfig = os.path.join(FRONTEND_DIR, "tsconfig.json")
    assert os.path.exists(tsconfig), (
        "frontend/tsconfig.json is required so `tsc --noEmit` can validate the source"
    )

    pkg = _read(os.path.join(FRONTEND_DIR, "package.json"))
    scripts = json.loads(pkg)["scripts"]
    assert "typecheck" in scripts, "package.json needs a 'typecheck' script"
    assert "tsc --noEmit" in scripts["typecheck"], (
        "the typecheck script must run tsc --noEmit"
    )
    assert "typecheck" in scripts["build"], (
        "the build script must run the typecheck before vite build"
    )


@pytest.mark.slow
def test_frontend_production_build_clean():
    """Verify the full build (typecheck + bundle) succeeds."""
    res = subprocess.run(
        ["npm.cmd", "run", "build"],
        cwd=FRONTEND_DIR,
        capture_output=True,
        text=True,
        shell=True,
    )
    assert res.returncode == 0, f"Frontend build failed:\nSTDOUT:\n{res.stdout}\nSTDERR:\n{res.stderr}"


if __name__ == "__main__":
    pytest.main(["-v", __file__])
